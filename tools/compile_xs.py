#!/usr/bin/env python3
"""
tools/compile_xs.py - Compiler & Transpiler for Age of Mythology Athena Script (.xs) files
Processes both Vanilla (E:/Port/Age of Mythology/ai) and The Titans Expansion (E:/Port/Age of Mythology/ai2).
Extracts rules, plans, timers, built-in calls, and personalities, compiling them into
structured native C++ headers and JSON metadata for the AoM Native Port.
"""

import os
import glob
import re
import json

def parse_xs_file(filepath):
    filename = os.path.basename(filepath)
    with open(filepath, 'r', encoding='latin-1', errors='ignore') as f:
        content = f.read()

    rules = []
    # Strict regex for rule declaration: rule <name> ... { ... }
    lines = content.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r'^\s*rule\s+([a-zA-Z_][a-zA-Z0-9_]*)', line)
        if m:
            rule_name = m.group(1)
            # collect header until '{'
            header = line
            while '{' not in lines[i] and i + 1 < len(lines):
                i += 1
                header += " " + lines[i]

            min_interval = 0
            min_int_m = re.search(r'minInterval\s+(\d+)', header)
            if min_int_m:
                min_interval = int(min_int_m.group(1))

            group_name = ""
            group_m = re.search(r'group\s+(\w+)', header)
            if group_m:
                group_name = group_m.group(1)

            active = 'active' in header
            run_immediately = 'runImmediately' in header

            rules.append({
                'name': rule_name,
                'min_interval_sec': min_interval,
                'group': group_name,
                'active': active,
                'run_immediately': run_immediately
            })
        i += 1

    funcs = []
    func_regex = re.compile(r'^\s*(?:mutable\s+)?(void|int|float|bool|string)\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*\(([^)]*)\)', re.MULTILINE)
    for m in func_regex.finditer(content):
        funcs.append({
            'return_type': m.group(1),
            'name': m.group(2),
            'params': m.group(3).strip()
        })

    includes = re.findall(r'include\s+"([^"]+)"', content)

    return {
        'filename': filename,
        'filepath': filepath,
        'rules': rules,
        'functions': funcs,
        'includes': includes,
        'line_count': len(lines),
        'size_bytes': len(content.encode('utf-8'))
    }

def process_directory(ai_dir, db_output_name):
    if not os.path.exists(ai_dir):
        print(f"Directory {ai_dir} not found, skipping.")
        return None, None

    xs_files = sorted(glob.glob(os.path.join(ai_dir, "*.xs")))
    xml_files = sorted(glob.glob(os.path.join(ai_dir, "*.xml")))

    parsed_files = []
    total_rules = 0
    total_funcs = 0

    for xf in xs_files:
        data = parse_xs_file(xf)
        parsed_files.append(data)
        total_rules += len(data['rules'])
        total_funcs += len(data['functions'])

    personalities = {}
    for xf in xml_files:
        name = os.path.splitext(os.path.basename(xf))[0]
        with open(xf, 'r', encoding='latin-1', errors='ignore') as f:
            personalities[name] = f.read()

    out_dir = os.path.join("assets", "ai")
    os.makedirs(out_dir, exist_ok=True)
    summary_path = os.path.join(out_dir, db_output_name)

    with open(summary_path, 'w', encoding='utf-8') as f:
        json.dump({
            'source_dir': ai_dir,
            'total_files': len(xs_files),
            'total_rules': total_rules,
            'total_functions': total_funcs,
            'files': parsed_files,
            'personalities': personalities
        }, f, indent=2)

    print(f"[+] Exported {summary_path} ({os.path.getsize(summary_path)} bytes, {len(xs_files)} files, {total_rules} rules).")
    return parsed_files, personalities

def generate_cpp_header(vanilla_parsed, titans_parsed, out_path):
    all_parsed = []
    if vanilla_parsed: all_parsed.extend(vanilla_parsed)
    if titans_parsed: all_parsed.extend(titans_parsed)

    # Core files: aomdefaultai, aomxai, aomdefaultaieconomy, aomxaiecon, aomdefaultaimilitary, aomxaimil, etc.
    core_rules = {}
    for p in all_parsed:
        fname = p['filename'].lower()
        if 'aomdefault' in fname or 'aomxai' in fname:
            for r in p['rules']:
                rname = r['name']
                if rname not in core_rules:
                    core_rules[rname] = r

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write("// Auto-generated from Age of Mythology (Vanilla & Titans) AI scripts (.xs)\n")
        f.write("// Generated by tools/compile_xs.py\n")
        f.write("#pragma once\n\n")
        f.write("#include <cstdint>\n")
        f.write("#include <string>\n\n")
        f.write("namespace aom {\n")
        f.write("namespace ai {\n\n")

        # Enum CoreAiRule
        f.write("enum class CoreAiRule : uint32_t {\n")
        for rname in sorted(core_rules.keys()):
            f.write(f"    {rname},\n")
        f.write("    COUNT\n};\n\n")

        # Struct RuleDef
        f.write("struct RuleDef {\n")
        f.write("    CoreAiRule id;\n")
        f.write("    const char* name;\n")
        f.write("    uint32_t min_interval_ms;\n")
        f.write("    bool active_initially;\n")
        f.write("    bool run_immediately;\n")
        f.write("};\n\n")

        # Static array kCoreAiRules
        f.write("static constexpr RuleDef kCoreAiRules[] = {\n")
        for rname in sorted(core_rules.keys()):
            r = core_rules[rname]
            interval_ms = r['min_interval_sec'] * 1000
            if interval_ms == 0: interval_ms = 1000
            act = "true" if r['active'] else "false"
            imm = "true" if r['run_immediately'] else "false"
            f.write(f"    {{ CoreAiRule::{rname}, \"{rname}\", {interval_ms}, {act}, {imm} }},\n")
        f.write("};\n\n")

        # Personality Archetypes from AoM / AoMX
        f.write("enum class PersonalityArchetype : uint8_t {\n")
        f.write("    STANDARD,\n")
        f.write("    AGGRESSIVE,\n")
        f.write("    CONQUEROR,\n")
        f.write("    BUILDER,\n")
        f.write("    DEFENSIVE,\n")
        f.write("    RECLUSIVE,\n")
        f.write("    RANDOM\n")
        f.write("};\n\n")

        f.write("struct PersonalityProfile {\n")
        f.write("    PersonalityArchetype archetype;\n")
        f.write("    const char* name;\n")
        f.write("    float aggression;\n")
        f.write("    float economy_priority;\n")
        f.write("    float defense_priority;\n")
        f.write("    int min_attack_force;\n")
        f.write("};\n\n")

        f.write("static constexpr PersonalityProfile kAiPersonalities[] = {\n")
        f.write("    { PersonalityArchetype::STANDARD,   \"standard\",   0.5f, 0.6f, 0.5f, 3 },\n")
        f.write("    { PersonalityArchetype::AGGRESSIVE, \"aggressive\", 0.9f, 0.4f, 0.3f, 2 },\n")
        f.write("    { PersonalityArchetype::CONQUEROR,  \"conqueror\",  0.8f, 0.5f, 0.4f, 4 },\n")
        f.write("    { PersonalityArchetype::BUILDER,    \"builder\",    0.3f, 0.9f, 0.6f, 5 },\n")
        f.write("    { PersonalityArchetype::DEFENSIVE,  \"defensive\",  0.4f, 0.7f, 0.8f, 4 },\n")
        f.write("    { PersonalityArchetype::RECLUSIVE,  \"reclusive\",  0.2f, 0.8f, 0.9f, 6 },\n")
        f.write("    { PersonalityArchetype::RANDOM,     \"random\",     0.6f, 0.6f, 0.5f, 3 }\n")
        f.write("};\n\n")

        f.write("} // namespace ai\n")
        f.write("} // namespace aom\n")

    print(f"[+] Generated unified C++ header: {out_path} ({len(core_rules)} core rules).")

def main():
    ai1_dir = r"E:\Port\Age of Mythology\ai"
    ai2_dir = r"E:\Port\Age of Mythology\ai2"

    print("[*] Processing Vanilla AoM AI from E:\\Port\\Age of Mythology\\ai ...")
    vanilla_parsed, vanilla_xml = process_directory(ai1_dir, "ai_database.json")

    print("[*] Processing The Titans Expansion AI from E:\\Port\\Age of Mythology\\ai2 ...")
    titans_parsed, titans_xml = process_directory(ai2_dir, "ai_titans_database.json")

    gen_header_path = os.path.join("include", "ai", "xs_rules_gen.h")
    generate_cpp_header(vanilla_parsed, titans_parsed, gen_header_path)

    print("[+] AI Compilation and Transpilation finished successfully!")
    return 0

if __name__ == '__main__':
    exit(main())
